local root=game:GetService('CoreGui'):WaitForChild('RobloxGui')
local modules=root:WaitForChild('Modules');local http=game:GetService('HttpService')
local bridge=modules:WaitForChild('LocalLibraryBridge')
local gui=game:GetService('GuiService')
local function request(op,body)return http:JSONDecode(bridge:Profile(op,body and http:JSONEncode(body)or''))end
local function find(parent,name)
 if parent.Name==name and parent:IsA('GuiObject') then return parent end
 for _,child in pairs(parent:GetChildren())do local result=find(child,name);if result then return result end end
end
local function press(name,key)
 gui.SelectedCoreObject=assert(find(root,name),'Original tile missing: '..name);wait(.3)
 print('[DetailsTest] Input '..(key or 'X'));wait(2)
end
wait(10)
local profile=request('get');local appearance=profile.appearance
appearance.body_package=nil;appearance.clothing.shirt=nil;appearance.accessories={}
request('save',{profile_version=profile.profile_version,appearance=appearance})
appearance.body_package=900100002;appearance.clothing.shirt=900100001;appearance.accessories={900100003}
local outfit=request('outfit-save',{name='Collection Outfit',appearance=appearance})
local events=require(modules.EventHub)
events:dispatchEvent(events.Notifications.NavigateToEquippedAvatar)
wait(7)
local pane=assert(find(root,'AvatarPane'),'Actual original AvatarPane missing')
assert(pane.Visible and find(pane,'MyAvatarContainer') and find(pane,'SelectableAvatarsContainer'),'Original hierarchy missing')
assert(not workspace:FindFirstChild('LocalAvatarPreview'),'3D preview substituted for collection')
assert(not find(root,'LocalAvatarEditor'),'Replacement collection still running')
gui.SelectedCoreObject=assert(find(pane,'LocalCollectionAsset_900100003'),'Original inventory tile missing')
wait(.5)
local first=assert(gui.SelectedCoreObject,'Original focus missing')
print('[OriginalCollectionTest] Initial focus '..first.Name..' right='..tostring(first.NextSelectionRight))
print('[DetailsTest] Input Right');wait(2)
assert(gui.SelectedCoreObject and gui.SelectedCoreObject~=first and gui.SelectedCoreObject:IsDescendantOf(pane),'Original D-pad grid navigation failed')
print('[OriginalCollectionTest] Original hierarchy and real D-pad navigation PASS')
press('LocalCollectionAsset_900100001')
assert(request('get').appearance.clothing.shirt==900100001,'Original X did not persist shirt')
press('LocalCollectionAsset_900100003')
assert(request('get').appearance.accessories[1]==900100003,'Accessory not persisted')
press('LocalCollectionAsset_900100002','A')
assert(request('get').appearance.body_package==900100002,'Original owned tile A did not persist package')
press('LocalCollectionOutfit_'..outfit.outfit_id)
assert(request('get').equipped_outfit_id==outfit.outfit_id,'Original OutfitTile did not persist outfit')
print('[OriginalCollectionTest] Original AvatarTile and OutfitTile equip/profile persistence PASS')
print('[DetailsTest] Page ready original collection');wait(3)
print('[AvatarEditorTest] Resize requested');wait(3)
print('[DetailsTest] Page ready original collection resized');wait(3)
local library=require(modules.LocalGameLibrary);library.Refresh()
events:dispatchEvent(events.Notifications.OpenGameDetail,900000100,'MyTestPlace',false);wait(3)
press('PlayButton','A');wait(15)
game:GetService('PlatformService'):RequestGameShutdown();wait(4)
events:dispatchEvent(events.Notifications.NavigateToEquippedAvatar);wait(5)
assert(find(root,'AvatarPane').Visible,'Original collection did not return')
assert(request('get').equipped_outfit_id==outfit.outfit_id,'Saved outfit lost after game')
press('LocalCollectionAsset_900100001')
print('[DetailsTest] Page ready original collection returned');wait(3)
print('[OriginalCollectionTest] Original collection gameplay avatar and menu return PASS')
