local gui = game:GetService('CoreGui'):WaitForChild('RobloxGui')
local modules = gui:WaitForChild('Modules')
local account = require(modules:WaitForChild('OfflineAccountProfile'))
assert(account.Enabled and account.Profile.user_id > 0, 'Local account missing')
wait(5)
require(modules:WaitForChild('OfflineMenuPreview')).Begin()
wait(3)
local user = require(modules:WaitForChild('UserData'))
assert(user:GetRbxUserId() == account.Profile.user_id, 'Menu user ID mismatch')
assert(user:GetRobloxName() == account.Profile.username, 'Menu username mismatch')
assert(user:GetDisplayName() == account.Profile.display_name, 'Menu display name mismatch')
assert(gui:FindFirstChild('LocalAccountBadge'), 'Account badge missing')
print('ACCOUNT MENU PASS: original UserData matches authenticated profile, ID '..account.Profile.user_id)

