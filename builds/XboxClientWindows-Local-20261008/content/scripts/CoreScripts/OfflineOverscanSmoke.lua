wait(8)
local root = game:GetService('CoreGui'):FindFirstChild('RobloxGui')
local modules = root:FindFirstChild('Modules')
require(modules:FindFirstChild('OfflineMenuPreview')).Begin()
wait(3)
local screens = require(modules:FindFirstChild('ScreenManager'))
local screen = require(modules:FindFirstChild('OverscanScreen'))(root)
screens:OpenScreen(screen)
screen:SetAdjustmentEdges(Vector2.new(0.92, 0.94))
local edges = screen:GetAdjustmentEdgesPercent()
assert(math.abs(edges.X - 0.92) < 0.001 and math.abs(edges.Y - 0.94) < 0.001)
local options = settings():FindFirstChild('Game Options')
options.OverscanPX = edges.X
options.OverscanPY = edges.Y
assert(math.abs(options.OverscanPX - 0.92) < 0.001)
screen:ResetEdges()
assert(math.abs(screen:GetAdjustmentEdgesPercent().X - 0.9) < 0.001)
print('Offline overscan test: opened, adjusted, stored and reset original screen')
wait(5)
screens:CloseCurrent()
print('Offline overscan test: returned to original hub')
